import nltk
from collections import defaultdict
from nltk import word_tokenize , pos_tag

verb_prep_count = defaultdict(int)
noun_prep_count = defaultdict(int)
verb_count = defaultdict(int)
noun_count = defaultdict(int)

def extract_pairs(sentence):
    words = word_tokenize(sentence)
    tags = pos_tag(words)

    verb = None
    noun = None
    for word, tag in tags:

        if tag.startswith('V'):
            verb = word.lower()
            verb_count[verb] += 1

        elif tag.startswith('N'):
            noun = word.lower()
            noun_count[noun] += 1

        elif tag == 'IN':
            prep = word.lower()

            if verb:
                verb_prep_count[(verb, prep)] += 1
            if noun:
                noun_prep_count[(noun, prep)] += 1

