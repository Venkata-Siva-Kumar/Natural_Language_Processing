def hindle_rooth_decision(sentence):

    words = nltk.word_tokenize(sentence)
    tags = nltk.pos_tag(words)

    verb = None
    noun = None
    prep = None

    for word, tag in tags:
        if tag.startswith('V'):
            verb = word.lower()

        elif tag.startswith('N'):
            noun = word.lower()

        elif tag == 'IN':
            prep = word.lower()

    if not (verb and noun and prep):
        return "Insufficient data"

    # Probabilities
    pv = verb_prep_count[(verb, prep)] / (verb_count[verb] + 1e-6)
    pn = noun_prep_count[(noun, prep)] / (noun_count[noun] + 1e-6)


    print(f"\nSentence: {sentence}")
    print(f"Verb = {verb}")
    print(f"Noun = {noun}")
    print(f"Preposition = {prep}")
    print(f"P(prep|verb) = {round(pv)}")
    print(f"P(prep|noun) = {pn}")

    if pv > pn:
        return "Preposition attached to VERB"
    else:
        return "Preposition attached to NOUN"

